       CAST(NULL AS INT) PartID
INTO #c FROM #p WHERE Code LIKE 'C%' GROUP BY Code;   -- coil steel only (4C also moves B / D / H / M parts)
UPDATE c SET PartID = (SELECT MIN(P.PartID) FROM Nexus.Parts P WHERE P.PartCode = c.Code) FROM #c c;
IF EXISTS (SELECT 1 FROM Nexus.Parts P JOIN #c c ON c.Code = P.PartCode GROUP BY P.PartCode HAVING COUNT(*) > 1)
    BEGIN RAISERROR(N'Duplicate PartCode in CHR-Nexus - check before running', 16, 1); RETURN; END

-- masters: stock + reason to skip
SELECT m.Grp, m.Master, m.Code, CASE m.Grp WHEN '4C' THEN 1 ELSE 16 END StockID, CAST(NULL AS INT) PartID, CAST(NULL AS VARCHAR(20)) Skip
INTO #mm FROM #m m;
-- STORE-MAT master = text before the first "-" (DCAE3039D-2-010 -> DCAE3039D) · base too short (e.g. "1-65065122") = skip
UPDATE #mm SET Skip = 'BAD FORMAT' WHERE Grp = '4C' AND CHARINDEX('-', Master) BETWEEN 1 AND 5;
UPDATE #mm SET Master = LEFT(Master, CHARINDEX('-', Master) - 1) WHERE Grp = '4C' AND CHARINDEX('-', Master) > 5;
DELETE a FROM #mm a WHERE EXISTS (SELECT 1 FROM #mm b WHERE b.Grp = a.Grp AND b.Master = a.Master AND b.Code < a.Code);
UPDATE x SET PartID = (SELECT MIN(P.PartID) FROM Nexus.Parts P WHERE P.PartCode = x.Code) FROM #mm x;
UPDATE x SET Skip = CASE
        WHEN EXISTS (SELECT 1 FROM Nexus.Coils k WHERE k.CoilNo = x.Master) THEN 'COIL EXISTS'
        -- coils already registered under this number or its base (e.g. DCAC0379B-003-001 under master DCAC0379B) = leave as is
        WHEN EXISTS (SELECT 1 FROM Nexus.Coils k WHERE k.MotherCoil = x.Master OR k.CoilNo LIKE x.Master + '-%'
                        OR (CHARINDEX('-', x.Master) > 0 AND k.MotherCoil = LEFT(x.Master, CHARINDEX('-', x.Master) - 1))) THEN 'HAS CHILDREN'
        WHEN x.PartID IS NULL AND NOT EXISTS (SELECT 1 FROM #c c WHERE c.Code = x.Code) THEN 'NO PART'
        WHEN x.PartID IS NOT NULL AND NOT EXISTS (SELECT 1 FROM Nexus.Coils k WHERE k.PartID = x.PartID AND k.StockID = x.StockID)
             AND ((x.StockID = 1 AND EXISTS (SELECT 1 FROM Nexus.Parts P WHERE P.PartID = x.PartID AND (ISNULL(P.StockQuantity, 0) <> 0 OR ISNULL(P.CoilQuantity, 0) <> 0)))
               OR (x.StockID = 16 AND EXISTS (SELECT 1 FROM Nexus.PartStocks S WHERE S.PartID = x.PartID AND S.StockID = 16 AND (S.Quantity <> 0 OR S.BoxQuantity <> 0))))
             THEN 'STOCK NO COILS' END
FROM #mm x;
-- same master in 4C and 4L (CoilNo is unique): keep the PANTA row, mother coils live in STORE-PANTA
UPDATE x SET Skip = 'DUP MASTER' FROM #mm x WHERE x.Grp = '4C' AND Skip IS NULL AND EXISTS (SELECT 1 FROM #mm y WHERE y.Master = x.Master AND y.Grp = '4L');
IF EXISTS (SELECT 1 FROM #mm WHERE Skip IS NULL GROUP BY Master HAVING COUNT(*) > 1)
    BEGIN RAISERROR(N'Duplicate master coil in source - nothing was changed', 16, 1); RETURN; END

