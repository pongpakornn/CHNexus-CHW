/* =====================================================================
   🔄 EDP: ปรับแผนใน CHR-Nexus ให้ตรงกับโปรแกรม EDP Systems (.exe · ฐาน EDP_SYSTEM)
   - EDP_SYSTEM อ่านอย่างเดียว (SELECT) · เขียนเฉพาะ schema EDP ใน CHR-Nexus
   - หัวแผน: สถานะ / วันที่ / กะ ตาม EDP_SYSTEM · ที่ยังไม่มี = เพิ่ม (เลข PLH_ID เดิม)
   - การ์ด: เลข PLD_ID เดิม · ที่ EDP_SYSTEM ไม่มีแล้ว (ถูก SAVE ALL / ลงแม่แบบใหม่ที่ .exe) = เอาออก · ที่ยังไม่มี = เพิ่ม · ค่าไม่ตรง = แก้
   - ชิ้นงาน: PT_ID ของ EDP_SYSTEM -> Nexus PartID (จับคู่ PT_CODE = PartA ในคลัง STORE-PC แบบ 26_EDP_Planning.sql)
   - Log แก้ไขการ์ด (ฐานคิด HG ตั้งต้น): เพิ่มแถวที่ยังไม่มี
   รันซ้ำได้ (ไม่มีอะไรต่าง = ไม่แก้อะไร)
   ===================================================================== */
SET NOCOUNT ON;
SET XACT_ABORT ON;
IF DB_NAME() <> 'CHR-Nexus' THROW 50000, N'ต้องรันบนฐาน CHR-Nexus', 1;
IF DB_ID('EDP_SYSTEM') IS NULL THROW 50001, N'ไม่พบฐาน EDP_SYSTEM', 1;

BEGIN TRAN;

DECLARE @pc INT = (SELECT StockID FROM Nexus.Stocks WHERE StockCode = 'STORE-PC');
DECLARE @map TABLE (OLD_ID INT PRIMARY KEY, PartID INT);
INSERT INTO @map (OLD_ID, PartID)
SELECT M.PT_ID, MIN(P.PartID)
FROM EDP_SYSTEM.dbo.MST_PART M
JOIN Nexus.Parts P ON P.PartA = M.PT_CODE
JOIN Nexus.PartStocks S ON S.PartID = P.PartID AND S.StockID = @pc
GROUP BY M.PT_ID;

DECLARE @r TABLE (Step VARCHAR(30), N INT);

-- 1) หัวแผน
UPDATE N SET N.PLH_DATE = E.PLH_DATE, N.SHIFT = E.SHIFT, N.STAT = E.STAT
FROM EDP.PlanHeaders N JOIN EDP_SYSTEM.dbo.TRN_PLAN_H E ON E.PLH_ID = N.PLH_ID
WHERE N.PLH_DATE <> E.PLH_DATE OR N.SHIFT <> E.SHIFT OR ISNULL(N.STAT, '') <> ISNULL(E.STAT, '');
INSERT INTO @r VALUES ('headers_updated', @@ROWCOUNT);

SET IDENTITY_INSERT EDP.PlanHeaders ON;
INSERT INTO EDP.PlanHeaders (PLH_ID, PLH_DATE, SHIFT, STAT, CREATE_BY, CREATE_AT)
SELECT E.PLH_ID, E.PLH_DATE, E.SHIFT, E.STAT, E.CREATE_BY, E.CREATE_AT
FROM EDP_SYSTEM.dbo.TRN_PLAN_H E
WHERE NOT EXISTS (SELECT 1 FROM EDP.PlanHeaders N WHERE N.PLH_ID = E.PLH_ID);
INSERT INTO @r VALUES ('headers_added', @@ROWCOUNT);
SET IDENTITY_INSERT EDP.PlanHeaders OFF;

-- 2) การ์ดที่ .exe ไม่มีแล้ว
DELETE N FROM EDP.PlanCards N
WHERE NOT EXISTS (SELECT 1 FROM EDP_SYSTEM.dbo.TRN_PLAN_D E WHERE E.PLD_ID = N.PLD_ID);
INSERT INTO @r VALUES ('cards_removed', @@ROWCOUNT);

-- 3) การ์ดที่ค่าไม่ตรง
UPDATE N SET N.PLH_ID = E.PLH_ID, N.PT_ID = X.PartID, N.TIME_START = E.TIME_START, N.TIME_END = E.TIME_END,
             N.QTY_PLAN = E.QTY_PLAN, N.HG_PLAN = E.HG_PLAN, N.QTY_ACT = E.QTY_ACT, N.HG_ACT = E.HG_ACT, N.REMARK = E.REMARK,
             N.IS_DONE = E.IS_DONE, N.IS_VISIBLE = E.IS_VISIBLE, N.IS_PROBLEM = E.IS_PROBLEM, N.ROUND_ID = E.ROUND_ID,
             N.OP_NAME = E.OP_NAME, N.QTY_DIFF = E.QTY_DIFF, N.CUR_STD_TIME_HG = E.CUR_STD_TIME_HG, N.TOTAL_TIME_MIN = E.TOTAL_TIME_MIN,
             N.TIME_DIFF_MIN = E.TIME_DIFF_MIN, N.ACCUM_DIFF_MIN = E.ACCUM_DIFF_MIN
FROM EDP.PlanCards N
JOIN EDP_SYSTEM.dbo.TRN_PLAN_D E ON E.PLD_ID = N.PLD_ID
LEFT JOIN @map X ON X.OLD_ID = E.PT_ID
WHERE EXISTS (SELECT N.PLH_ID, N.PT_ID, N.TIME_START, N.TIME_END, N.QTY_PLAN, N.HG_PLAN, N.QTY_ACT, N.HG_ACT, N.REMARK, N.IS_DONE, N.IS_VISIBLE, N.IS_PROBLEM, N.ROUND_ID, N.OP_NAME
              EXCEPT
              SELECT E.PLH_ID, X.PartID, E.TIME_START, E.TIME_END, E.QTY_PLAN, E.HG_PLAN, E.QTY_ACT, E.HG_ACT, E.REMARK, E.IS_DONE, E.IS_VISIBLE, E.IS_PROBLEM, E.ROUND_ID, E.OP_NAME);
INSERT INTO @r VALUES ('cards_updated', @@ROWCOUNT);

-- 4) การ์ดที่ยังไม่มี
SET IDENTITY_INSERT EDP.PlanCards ON;
INSERT INTO EDP.PlanCards (PLD_ID, PLH_ID, PT_ID, TIME_START, TIME_END, QTY_PLAN, HG_PLAN, QTY_ACT, REMARK, IS_DONE, QTY_DIFF, OP_NAME,
                           CUR_STD_TIME_HG, HG_ACT, TOTAL_TIME_MIN, TIME_DIFF_MIN, ACCUM_DIFF_MIN, IS_VISIBLE, IS_PROBLEM, ROUND_ID)
SELECT E.PLD_ID, E.PLH_ID, X.PartID, E.TIME_START, E.TIME_END, E.QTY_PLAN, E.HG_PLAN, E.QTY_ACT, E.REMARK, E.IS_DONE, E.QTY_DIFF, E.OP_NAME,
       E.CUR_STD_TIME_HG, E.HG_ACT, E.TOTAL_TIME_MIN, E.TIME_DIFF_MIN, E.ACCUM_DIFF_MIN, E.IS_VISIBLE, E.IS_PROBLEM, E.ROUND_ID
FROM EDP_SYSTEM.dbo.TRN_PLAN_D E LEFT JOIN @map X ON X.OLD_ID = E.PT_ID
WHERE NOT EXISTS (SELECT 1 FROM EDP.PlanCards N WHERE N.PLD_ID = E.PLD_ID);
INSERT INTO @r VALUES ('cards_added', @@ROWCOUNT);
SET IDENTITY_INSERT EDP.PlanCards OFF;

-- 5) Log แก้ไขการ์ด: ให้ตรงกับ EDP_SYSTEM ทุกแถว (HG ก่อนแก้ครั้งแรก = ฐานคิดเวลาของการ์ด) · แถวที่ทำจากเว็บ = เอาออก
DELETE N FROM EDP.PlanEditLogs N
WHERE NOT EXISTS (SELECT 1 FROM EDP_SYSTEM.dbo.TRN_PLAN_EDIT_LOG E WHERE E.LOG_ID = N.LOG_ID AND E.PLD_ID = N.PLD_ID);
INSERT INTO @r VALUES ('edit_logs_removed', @@ROWCOUNT);
SET IDENTITY_INSERT EDP.PlanEditLogs ON;
INSERT INTO EDP.PlanEditLogs (LOG_ID, PLD_ID, OLD_CUST, OLD_PT_NO, OLD_QTY_PLAN, OLD_HG_PLAN, NEW_CUST, NEW_PT_NO, NEW_QTY_PLAN, NEW_HG_PLAN, IS_PROBLEM, REMARK, EDIT_BY, EDIT_DATE)
SELECT E.LOG_ID, E.PLD_ID, E.OLD_CUST, E.OLD_PT_NO, E.OLD_QTY_PLAN, E.OLD_HG_PLAN, E.NEW_CUST, E.NEW_PT_NO, E.NEW_QTY_PLAN, E.NEW_HG_PLAN, E.IS_PROBLEM, E.REMARK, E.EDIT_BY, E.EDIT_DATE
FROM EDP_SYSTEM.dbo.TRN_PLAN_EDIT_LOG E
WHERE NOT EXISTS (SELECT 1 FROM EDP.PlanEditLogs N WHERE N.LOG_ID = E.LOG_ID);
INSERT INTO @r VALUES ('edit_logs_added', @@ROWCOUNT);
SET IDENTITY_INSERT EDP.PlanEditLogs OFF;

-- 6) Log แก้เวลา / สลับการ์ด (TRN_PLAN_D_TIMEFIX_LOG): ให้ตรงกับ EDP_SYSTEM ทุกแถว (แถวที่ทดสอบจากเว็บ = เอาออก)
DELETE N FROM EDP.PlanTimeFixLogs N
WHERE NOT EXISTS (SELECT 1 FROM EDP_SYSTEM.dbo.TRN_PLAN_D_TIMEFIX_LOG E WHERE E.FIX_ID = N.FIX_ID AND E.PLD_ID = N.PLD_ID);
INSERT INTO @r VALUES ('timefix_removed', @@ROWCOUNT);
SET IDENTITY_INSERT EDP.PlanTimeFixLogs ON;
INSERT INTO EDP.PlanTimeFixLogs (FIX_ID, PLD_ID, OLD_TIME_START, NEW_TIME_START, OLD_ROUND_ID, NEW_ROUND_ID, FIXED_AT)
SELECT E.FIX_ID, E.PLD_ID, E.OLD_TIME_START, E.NEW_TIME_START, E.OLD_ROUND_ID, E.NEW_ROUND_ID, E.FIXED_AT
FROM EDP_SYSTEM.dbo.TRN_PLAN_D_TIMEFIX_LOG E
WHERE NOT EXISTS (SELECT 1 FROM EDP.PlanTimeFixLogs N WHERE N.FIX_ID = E.FIX_ID);
INSERT INTO @r VALUES ('timefix_added', @@ROWCOUNT);
SET IDENTITY_INSERT EDP.PlanTimeFixLogs OFF;

-- 7) ค่า HG ของชิ้นงาน (MST_PART -> ช่องเพิ่มเองของ STORE-PC) ให้ตรงกับ .exe : HG TYPE · PCS/HG · HG QTY · CT (SEC) · STD TIME (MIN.)
--    ค่าไม่ตรง = HG <-> PCS และเวลาที่ยืด / หดตาม HG บนเว็บไม่ตรงกับ .exe · จับคู่ชิ้นงานด้วย PT_CODE = PART A ของ STORE-PC
--    แก้เฉพาะค่าที่ต่างจริง (ตัวเลขเทียบเป็นตัวเลข ไม่สนรูปแบบ เช่น 3 กับ 3.00) · เขียนเฉพาะ Nexus.PartFieldValues (CHR-Nexus)
DECLARE @pv TABLE (PartID INT, FieldID INT, Val NVARCHAR(100), Num BIT);
INSERT INTO @pv (PartID, FieldID, Val, Num)
SELECT X.PartID, D.FieldID, V.Val, V.Num
FROM @map X
JOIN EDP_SYSTEM.dbo.MST_PART M ON M.PT_ID = X.OLD_ID
CROSS APPLY (VALUES (N'HG TYPE', NULLIF(LTRIM(RTRIM(M.HG_TYPE)), N''), CAST(0 AS BIT)),
                    (N'PCS/HG', CONVERT(NVARCHAR(100), M.PCS_HG), CAST(1 AS BIT)),
                    (N'HG QTY', CONVERT(NVARCHAR(100), M.QTY_HG), CAST(1 AS BIT)),
                    (N'CT (SEC)', CONVERT(NVARCHAR(100), M.STD_CT), CAST(1 AS BIT)),
                    (N'STD TIME (MIN.)', CONVERT(NVARCHAR(100), M.STD_TIME_HG), CAST(1 AS BIT))) V(Label, Val, Num)
JOIN Nexus.PartFieldDefs D ON D.StockID = @pc AND D.Label = V.Label
WHERE V.Val IS NOT NULL;

UPDATE F SET F.Value = P.Val, F.UpdatedAt = SYSDATETIME(), F.UpdatedBy = N'EDP_SYNC'
FROM Nexus.PartFieldValues F JOIN @pv P ON P.PartID = F.PartID AND P.FieldID = F.FieldID
WHERE (P.Num = 1 AND ISNULL(TRY_CAST(F.Value AS DECIMAL(18, 4)), -999999) <> TRY_CAST(P.Val AS DECIMAL(18, 4)))
   OR (P.Num = 0 AND ISNULL(F.Value, N'') <> P.Val);
INSERT INTO @r VALUES ('part_hg_updated', @@ROWCOUNT);

INSERT INTO Nexus.PartFieldValues (FieldID, PartID, Value, UpdatedAt, UpdatedBy)
SELECT P.FieldID, P.PartID, P.Val, SYSDATETIME(), N'EDP_SYNC'
FROM @pv P
WHERE NOT EXISTS (SELECT 1 FROM Nexus.PartFieldValues F WHERE F.PartID = P.PartID AND F.FieldID = P.FieldID);
INSERT INTO @r VALUES ('part_hg_added', @@ROWCOUNT);

COMMIT;

SELECT Step, N FROM @r;
SELECT (SELECT COUNT(*) FROM EDP.PlanCards) AS NexusCards, (SELECT COUNT(*) FROM EDP_SYSTEM.dbo.TRN_PLAN_D) AS ExeCards,
       (SELECT COUNT(*) FROM EDP.PlanCards N WHERE NOT EXISTS (SELECT 1 FROM EDP_SYSTEM.dbo.TRN_PLAN_D E WHERE E.PLD_ID = N.PLD_ID)) AS OnlyNexus,
       (SELECT COUNT(*) FROM EDP_SYSTEM.dbo.TRN_PLAN_D E WHERE NOT EXISTS (SELECT 1 FROM EDP.PlanCards N WHERE N.PLD_ID = E.PLD_ID)) AS OnlyExe;
-- ค่า HG ของชิ้นงานที่ยังไม่ตรงกับ MST_PART (ควรเป็น 0)
SELECT COUNT(*) AS PartHgDiff FROM EDP_SYSTEM.dbo.MST_PART M JOIN EDP.vw_Parts V ON LTRIM(RTRIM(V.PT_CODE)) = LTRIM(RTRIM(M.PT_CODE))
WHERE ISNULL(V.QTY_HG, -1) <> ISNULL(M.QTY_HG, -1) OR ISNULL(V.PCS_HG, -1) <> ISNULL(M.PCS_HG, -1)
   OR ISNULL(V.STD_CT, -1) <> ISNULL(M.STD_CT, -1) OR ISNULL(V.STD_TIME_HG, 3.25) <> ISNULL(M.STD_TIME_HG, 3.25);
GO
